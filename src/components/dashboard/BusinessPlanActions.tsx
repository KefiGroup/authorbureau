export default function BusinessPlanActions({
  content,
  bookId,
  bookTitle,
  authorId,
}: BusinessPlanActionsProps) {
  const [downloading, setDownloading] = useState(false);
  const [saved, setSaved] = useState(false);
  const [checkoutTierLoading, setCheckoutTierLoading] = useState<keyof typeof TIERS | null>(null);
  const { toast } = useToast();
  const { isPremium, isAdmin } = useAuth();
  const savedRef = useRef(false);

  // Auto-save the business plan via edge function (bypasses RLS)
  useEffect(() => {
    if (savedRef.current) return;
    savedRef.current = true;

    (async () => {
      try {
        const { data: { session } } = await sharedSupabase.auth.getSession();
        const token = session?.access_token;
        const resp = await fetch(`${import.meta.env.VITE_SUPABASE_URL}/functions/v1/business-consultant`, {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
            Authorization: `Bearer ${token || import.meta.env.VITE_SUPABASE_PUBLISHABLE_KEY}`,
          },
          body: JSON.stringify({ action: "save-plan", bookId, content }),
        });
        if (resp.ok) setSaved(true);
      } catch (err) {
        console.error("Failed to save business plan:", err);
      }
    })();
  }, [bookId, authorId, content]);

  const handleSubscribe = async (tier: keyof typeof TIERS) => {
    setCheckoutTierLoading(tier);
    const popup = window.open("about:blank", "_blank");
    try {
      const { data, error } = await sharedSupabase.functions.invoke("create-checkout", {
        body: { priceId: TIERS[tier].price_id, source_platform: "authorsbureau" },
      });
      if (error) throw error;
      if (data?.url && popup) {
        popup.location.href = data.url;
      } else if (data?.url) {
        window.location.href = data.url;
      }
    } catch (err) {
      popup?.close();
      toast({
        title: "Could not start checkout",
        description: err?.message || "Please try again.",
        variant: "destructive",
      });
    } finally {
      setCheckoutTierLoading(null);
    }
  };

  const handleDownload = async () => {
    setDownloading(true);
    try {
      const html = generateDocxHtml(content);
      printExportHtml(html, `ABBY Business Plan - ${bookTitle}`);
      toast({
        title: "Downloaded!",
        description: "Your ABBY Business Plan is ready to save as PDF.",
      });
    } catch (err) {
      console.error("Download failed:", err);
      toast({
        title: "Download failed",
        description: "Please try again.",
        variant: "destructive",
      });
    } finally {
      setDownloading(false);
    }
  };

  return (
    <div className="mt-4 space-y-3">
      <div className="flex items-center gap-3 flex-wrap">
        <Button
          onClick={handleDownload}
          disabled={downloading}
          variant="outline"
          size="sm"
          className="gap-2"
        >
          {downloading ? (
            <>
              <Loader2 className="h-3.5 w-3.5 animate-spin" /> Generating…
            </>
          ) : (
            <>
              <Download className="h-3.5 w-3.5" /> Download PDF
            </>
          )}
        </Button>
        {saved && (
          <span className="flex items-center gap-1 text-[11px] text-muted-foreground">
            <Check className="h-3 w-3 text-accent" /> Plan saved
          </span>
        )}
      </div>

      {!(isPremium || isAdmin) && (
        <div className="rounded-lg border border-border bg-muted/30 p-3">
          <p className="text-xs font-medium text-foreground mb-2 flex items-center gap-1.5">
            <Crown className="h-3.5 w-3.5 text-secondary" /> Subscribe to start building now
          </p>
          <div className="flex flex-wrap gap-2">
            {(["brand", "build", "yield"] as const).map((tierKey) => (
              <Button
                key={tierKey}
                size="sm"
                variant={tierKey === "brand" ? "default" : "outline"}
                className="gap-1.5"
                onClick={() => handleSubscribe(tierKey)}
                disabled={checkoutTierLoading !== null}
              >
                {checkoutTierLoading === tierKey ? (
                  <Loader2 className="h-3.5 w-3.5 animate-spin" />
                ) : (
                  <Crown className="h-3.5 w-3.5" />
                )}
                {TIERS[tierKey].label} (${TIERS[tierKey].monthlyPrice}/mo)
              </Button>
            ))}
          </div>
        </div>
      )}
    </div>
  );
}
