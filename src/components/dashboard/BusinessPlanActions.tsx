import { useState, useEffect, useRef } from "react";
import { Button } from "@/components/ui/button";
import { Download, Loader2, Check, Crown } from "lucide-react";
import { useToast } from "@/hooks/use-toast";
import { printExportHtml } from "@/lib/print-export";
import { supabase as sharedSupabase } from "@/lib/shared-backend";
import { TIERS, useAuth } from "@/hooks/useAuth";

interface BusinessPlanActionsProps {
  content: string;
  bookId: string;
  bookTitle: string;
  authorId: string;
}

/** Detect if a message contains an ABBY Business Plan */
export function isBusinessPlanMessage(content: string): boolean {
  const normalized = content.toLowerCase();

  // Legacy + current plan formats
  const markers = [
    "abby business plan",
    "your transformation promise",
    "starter package",
    "pro package",
    "enterprise package",
    "monetization map",
    "monetisation map",
    "unlock your plan",
    "section 6 — next steps",
    "section 6 - next steps",
    "subscribe to the recommended plan",
    "roi:",
    // New v2.5 format markers
    "brand products",
    "build authority",
    "yield revenue",
    "total projected revenue",
    "28-node revenue",
    "28 node revenue",
    "estimated revenue",
    "sub-phase a",
    "sub-phase b",
    "===show_full_plan===",
    "view your full 28-node",
    "show me how to unlock",
  ];

  const matchCount = markers.filter((m) => normalized.includes(m)).length;

  // Accept either rich legacy plans or current concise plan format
  return matchCount >= 2;
}

function markdownToHtml(md: string): string {
  let html = md
    // Headers
    .replace(/^### (.+)$/gm, "<h3>$1</h3>")
    .replace(/^## (.+)$/gm, "<h2>$1</h2>")
    .replace(/^# (.+)$/gm, "<h1>$1</h1>")
    // Bold
    .replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>")
    // Italic
    .replace(/\*(.+?)\*/g, "<em>$1</em>")
    // Ordered lists
    .replace(/^\d+\.\s+(.+)$/gm, "<li>$1</li>")
    // Unordered lists
    .replace(/^[-•]\s+(.+)$/gm, "<li>$1</li>")
    // Wrap consecutive <li> in <ul>
    .replace(/((?:<li>.*<\/li>\n?)+)/g, "<ul>$1</ul>")
    // Paragraphs (lines that aren't already HTML)
    .replace(/^(?!<[hulo])((?!<).+)$/gm, "<p>$1</p>")
    // Line breaks
    .replace(/\n\n/g, "<br/>");

  return html;
}

